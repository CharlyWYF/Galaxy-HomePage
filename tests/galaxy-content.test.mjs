import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as THREE from '../vendor/three.module.js';
import {parseGalaxyContent,buildRoutePairs} from '../galaxy-content.mjs';
const raw=JSON.parse(await readFile(new URL('../galaxy-content.json',import.meta.url),'utf8'));
const parsed=parseGalaxyContent(raw);
assert.equal(parsed.planets.length,raw.planets.length);
const small=['a','b','c'].map(id=>({id}));
const auto={mode:'auto',closed:true};
assert.deepEqual(buildRoutePairs([],auto),[]);
assert.deepEqual(buildRoutePairs(small.slice(0,1),auto),[]);
assert.deepEqual(buildRoutePairs(small.slice(0,2),auto),[['a','b']]);
assert.deepEqual(buildRoutePairs(small,auto),[['a','b'],['b','c'],['c','a']]);
assert.deepEqual(buildRoutePairs([...small,{id:'d'}],auto),[['a','b'],['b','c'],['c','d'],['d','a']]);
assert.deepEqual(buildRoutePairs([small[0],small[2]],auto),[['a','c']]);
assert.deepEqual(buildRoutePairs(small,{...auto,closed:false}),[['a','b'],['b','c']]);
assert.deepEqual(buildRoutePairs(small,{mode:'manual',links:[['a','c'],['c','a'],['a','a'],['a','removed'],['b','c']]}),[['a','c'],['b','c']]);
assert.deepEqual(buildRoutePairs([...small].reverse(),{mode:'manual',links:[['a','c']]}),[['a','c']]);
assert.deepEqual(buildRoutePairs(small,{mode:'none'}),[]);
const mixed=[{id:'a',group:'signal'},{id:'x',group:'tool'},{id:'b',group:'signal'},{id:'y',group:'tool'},{id:'c',group:'signal'},{id:'solo',group:'memory'}];
assert.deepEqual(buildRoutePairs(mixed,auto),[['a','b'],['b','c'],['c','a'],['x','y']]);
assert.deepEqual(buildRoutePairs(mixed,{...auto,closed:false}),[['a','b'],['b','c'],['x','y']]);
const groupsById=new Map(parsed.planets.map(n=>[n.id,n.group]));
for(const [a,b] of buildRoutePairs(parsed.planets,{...parsed.routes,mode:'auto'}))assert.equal(groupsById.get(a),groupsById.get(b),'automatic routes must stay within one sector');
const fixture={sectors:{tool:{label:'工具',name:'工具星区',sub:'TOOLS',x:0,z:0}},defaults:{radius:2},planets:[{id:'a',name:'A',url:'https://example.com/a',group:'tool',x:0,z:0},{id:'b',name:'B',url:'https://example.com/b',group:'tool',x:10,z:0}],routes:{}};
const edit=callback=>{const config=structuredClone(fixture);callback(config);return config;};
assert.throws(()=>parseGalaxyContent(edit(c=>c.planets[1].id=c.planets[0].id)),/id/);
assert.throws(()=>parseGalaxyContent(edit(c=>c.planets[0].group='missing')),/group/);
assert.throws(()=>parseGalaxyContent(edit(c=>c.planets[0].url='example.com')),/url/);
assert.throws(()=>parseGalaxyContent(edit(c=>c.planets[0].radius=-1)),/radius/);
assert.throws(()=>parseGalaxyContent(edit(c=>c.planets[0].color='red')),/color/);
assert.throws(()=>parseGalaxyContent(edit(c=>c.routes.opacity=2)),/opacity/);
assert.throws(()=>parseGalaxyContent(edit(c=>c.routes.links=[['a']])),/links/);
assert.equal(parseGalaxyContent(edit(c=>delete c.planets[0].radius)).planets[0].r,fixture.defaults.radius);
const withCategory=parseGalaxyContent(edit(c=>{c.sectors.blog={label:'博客',name:'博客星区',sub:'BLOG',x:10,z:20};c.planets.push({id:'new-blog',name:'新博客',url:'https://example.com',group:'blog',x:10,z:20});}));
assert.equal(withCategory.planets.at(-1).r,2);
assert.equal(withCategory.sectors.blog.label,'博客');
// Exercise the scene's actual route update against real Three.js geometry.
const source=await readFile(new URL('../galaxy.js',import.meta.url),'utf8');
const updateSource=source.slice(source.indexOf('function updateRoutes(){'),source.indexOf('\nupdateRoutes();'));
const routeGeo=new THREE.BufferGeometry();
const routes=new THREE.LineSegments(routeGeo,new THREE.LineDashedMaterial());
const sceneNodes=new Map([['a',{x:0,z:0,body:{visible:true}}],['b',{x:3,z:4,body:{visible:true}}],['c',{x:9,z:8,body:{visible:true}}]]);
const update=new Function('THREE','routePairs','nodesById','routeGeo','routes',updateSource+';return updateRoutes;')(THREE,[['a','b'],['b','c']],sceneNodes,routeGeo,routes);
update();
assert.equal(routeGeo.getAttribute('position').count,4);
assert.equal(routeGeo.getAttribute('lineDistance').getX(1),5);
sceneNodes.get('c').body.visible=false;update();
assert.equal(routeGeo.getAttribute('position').count,2);
sceneNodes.get('b').body.visible=false;update();
assert.equal(routes.visible,false);
assert.equal(routeGeo.getAttribute('position').count,0);
sceneNodes.get('b').body.visible=true;sceneNodes.get('c').body.visible=true;sceneNodes.get('b').x=6;update();
assert.equal(routes.visible,true);
assert.equal(routeGeo.getAttribute('position').getX(1),6);
assert.equal(routeGeo.getAttribute('position').count,4);
console.log('Content validation, automatic/manual routes and filtered Three.js geometry passed.');

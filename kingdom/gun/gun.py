def apex_gun_lookup(gun_name):
    """
    一个简单的 Apex 枪械信息查询函数。
    """
    # 使用字典存储枪械数据: '枪械名称': {'子弹类型': '...', '枪械类型': '...'}
    gun_data = {
        # 冲锋枪 (SMG)
        'R99': {'子弹类型': '轻型子弹', '枪械类型': '冲锋枪'},
        '转换者': {'子弹类型': '轻型子弹', '枪械类型': '冲锋枪'},
        '电能冲锋枪': {'子弹类型': '能量子弹', '枪械类型': '冲锋枪'},
        'CAR': {'子弹类型': '轻型子弹/重型子弹', '枪械类型': '冲锋枪'},

        # 突击步枪 (AR)
        '平行步枪': {'子弹类型': '重型子弹', '枪械类型': '突击步枪'},
        'R301': {'子弹类型': '轻型子弹', '枪械类型': '突击步枪'},
        '猎兽': {'子弹类型': '重型子弹', '枪械类型': '突击步枪'},

        # 轻机枪 (LMG)
        '喷火枪': {'子弹类型': '轻型子弹', '枪械类型': '轻机枪'},
        '专注轻机枪': {'子弹类型': '能量子弹', '枪械类型': '轻机枪'},

        # 霰弹枪 (Shotgun)
        '和平使者': {'子弹类型': '霰弹枪子弹', '枪械类型': '霰弹枪'},
        'EVA-8': {'子弹类型': '霰弹枪子弹', '枪械类型': '霰弹枪'},
        
        # 狙击枪 (Sniper)
        '长弓': {'子弹类型': '狙击子弹', '枪械类型': '狙击枪'},
        '克雷贝尔': {'子弹类型': '特殊子弹', '枪械类型': '狙击枪'},
    }

    # 统一将输入转换为大写，以避免大小写不匹配（例如输入'r99'也能找到'R99'）
    # 注意：对于中文名称，这步可能不太适用，但对于英文缩写枪械如R99很有效。
    gun_name = gun_name.upper()
    
    # 尝试在字典中查找枪械信息
    if gun_name in gun_data:
        info = gun_data[gun_name]
        print(f"\n--- 正在查询 {gun_name} 的信息 ---")
        print(f"子弹类型: {info['子弹类型']}")
        print(f"枪械类型: {info['枪械类型']}")
        print("---------------------------------")
    else:
        print(f"\n抱歉，在数据库中找不到枪械 '{gun_name}' 的信息。")
        print("请检查枪械名称是否正确。")


# --- 运行示例 ---

# 1. 示例：查询 R99
apex_gun_lookup('R99')

# 2. 示例：查询 R301 (忽略大小写)
apex_gun_lookup('r301')

# 3. 示例：查询一个中文名称的枪械
apex_gun_lookup('平行步枪')

